"""Route options from third-party routing engines.

Valhalla (truck costing, honours vehicle weight) is the primary provider. Its public
server rejects trips longer than ~1,500 km, so OSRM (car profile, durations slowed to
truck speeds) is the fallback. Both engines return fewer than three alternatives for
some trips; the remainder are generated by forcing the route through a via point
offset to either side of the corridor.
"""

import hashlib
import logging
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass

import requests
from django.conf import settings
from django.core.cache import cache

from apps.routing import geo
from apps.routing.geo import LatLon
from apps.routing.services.http import default_headers

logger = logging.getLogger(__name__)

ROUTE_COUNT = 3
EMPTY_TRUCK_LB = (
    35_000  # typical tractor + empty trailer; added to the load for gross weight
)
LB_PER_METRIC_TON = 2204.62
TRUCK_TOP_SPEED_MPH = 65
METERS_PER_MILE = 1609.344

# Generated alternatives must be meaningfully different and not absurdly slow.
MAX_OVERLAP = 0.85
MAX_DURATION_RATIO = 1.6
DETOUR_FRACTIONS = (0.15, 0.3)
CACHE_TTL_SECONDS = 60 * 60
REQUEST_TIMEOUT_SECONDS = 30
# Valhalla shapes have a vertex every few metres; ~10 m tolerance keeps them faithful.
STORE_TOLERANCE_DEG = 0.0001


class RoutingError(Exception):
    """Routing provider unavailable or returned an unusable response."""


class NoRouteFound(RoutingError):
    """The providers answered but no drivable route exists between the points."""


class _ProviderLimitExceeded(RoutingError):
    pass


@dataclass(frozen=True)
class Route:
    coords: list[LatLon]
    cum_miles: list[float]
    cum_seconds: list[float]
    label: str
    provider: str

    @property
    def distance_miles(self) -> float:
        return self.cum_miles[-1]

    @property
    def duration_seconds(self) -> float:
        return self.cum_seconds[-1]

    def seconds_at_mile(self, mile: float) -> float:
        return geo.interpolate(self.cum_miles, self.cum_seconds, mile)


def _build_route(
    coords: list[LatLon], segment_seconds: list[float], label: str, provider: str
) -> Route:
    """`segment_seconds[i]` is the travel time from coords[i] to coords[i + 1]."""
    cum_miles = geo.cumulative_miles(coords)
    cum_seconds = [0.0]
    for seconds in segment_seconds:
        cum_seconds.append(cum_seconds[-1] + seconds)
    keep = geo.simplify_indices(coords, STORE_TOLERANCE_DEG)
    return Route(
        coords=[coords[i] for i in keep],
        cum_miles=[cum_miles[i] for i in keep],
        cum_seconds=[cum_seconds[i] for i in keep],
        label=label,
        provider=provider,
    )


def _spread_time(
    coords: list[LatLon], start: int, end: int, seconds: float, out: list[float]
) -> None:
    """Distribute `seconds` over segments start..end-1 proportionally to their length."""
    lengths = [geo.haversine_miles(coords[i], coords[i + 1]) for i in range(start, end)]
    total = sum(lengths)
    for offset, length in enumerate(lengths):
        out[start + offset] += seconds * (length / total if total else 1 / len(lengths))


def _label_from_roads(road_miles: Counter) -> str:
    names = [name for name, _ in road_miles.most_common(2)]
    return "via " + " / ".join(names) if names else "Route"


class ValhallaProvider:
    name = "valhalla"

    def __init__(self, base_url: str):
        self.base_url = base_url.rstrip("/")

    def routes(
        self, locations: list[LatLon], load_lb: float, alternates: int
    ) -> list[Route]:
        gross_tons = min(EMPTY_TRUCK_LB + load_lb, 80_000) / LB_PER_METRIC_TON
        body = {
            "locations": [
                {
                    "lat": lat,
                    "lon": lon,
                    "type": "break" if i in (0, len(locations) - 1) else "through",
                }
                for i, (lat, lon) in enumerate(locations)
            ],
            "costing": "truck",
            "costing_options": {
                "truck": {
                    "weight": round(gross_tons, 2),
                    "top_speed": round(TRUCK_TOP_SPEED_MPH * 1.609),
                }
            },
            "alternates": alternates,
            "units": "miles",
            "directions_type": "maneuvers",
            "narrative": False,
        }
        try:
            response = requests.post(
                f"{self.base_url}/route",
                json=body,
                headers=default_headers(),
                timeout=REQUEST_TIMEOUT_SECONDS,
            )
        except requests.RequestException as exc:
            raise RoutingError(f"Valhalla request failed: {exc}") from exc
        data = (
            response.json()
            if response.headers.get("content-type", "").startswith("application/json")
            else {}
        )
        if response.status_code != 200:
            code = data.get("error_code")
            if code == 154:  # path distance exceeds the server's limit
                raise _ProviderLimitExceeded(data.get("error", "distance limit"))
            if code in (171, 442, 443):  # no route / no suitable edges near a location
                raise NoRouteFound(data.get("error", "No route found"))
            raise RoutingError(
                f"Valhalla error {response.status_code}: {data.get('error', response.text[:200])}"
            )
        trips = [data["trip"]] + [alt["trip"] for alt in data.get("alternates", [])]
        return [self._parse_trip(trip) for trip in trips]

    def _parse_trip(self, trip: dict) -> Route:
        coords: list[LatLon] = []
        segment_seconds: list[float] = []
        road_miles: Counter = Counter()
        for leg in trip["legs"]:
            shape = geo.decode_polyline(leg["shape"], precision=6)
            leg_seconds = [0.0] * (len(shape) - 1)
            for maneuver in leg.get("maneuvers", []):
                start, end = maneuver["begin_shape_index"], maneuver["end_shape_index"]
                if end > start:
                    _spread_time(shape, start, end, maneuver["time"], leg_seconds)
                if maneuver.get("highway") and maneuver.get("street_names"):
                    road_miles[maneuver["street_names"][0]] += maneuver["length"]
            # Consecutive legs share their junction point; leg_seconds[0] then becomes
            # the time from the previous leg's last point to shape[1].
            coords.extend(shape[1:] if coords else shape)
            segment_seconds.extend(leg_seconds)
        return _build_route(
            coords, segment_seconds, _label_from_roads(road_miles), self.name
        )


class OsrmProvider:
    name = "osrm"

    def __init__(self, base_url: str):
        self.base_url = base_url.rstrip("/")

    def routes(
        self, locations: list[LatLon], load_lb: float, alternates: int
    ) -> list[Route]:  # noqa: ARG002
        # OSRM's car profile has no vehicle-weight option; load_lb is accepted for interface parity.
        path = ";".join(f"{lon},{lat}" for lat, lon in locations)
        params = {
            "alternatives": (
                alternates if len(locations) == 2 and alternates else "false"
            ),
            "overview": "full",
            "geometries": "polyline6",
            "annotations": "duration",
            "steps": "true",  # needed for the leg summaries used as route labels
        }
        try:
            response = requests.get(
                f"{self.base_url}/route/v1/driving/{path}",
                params=params,
                headers=default_headers(),
                timeout=REQUEST_TIMEOUT_SECONDS,
            )
            data = response.json()
        except (requests.RequestException, ValueError) as exc:
            raise RoutingError(f"OSRM request failed: {exc}") from exc
        if data.get("code") == "NoRoute":
            raise NoRouteFound(data.get("message", "No route found"))
        if data.get("code") != "Ok":
            raise RoutingError(
                f"OSRM error: {data.get('code')} {data.get('message', '')}"
            )
        return [self._parse_route(route) for route in data["routes"]]

    def _parse_route(self, route: dict) -> Route:
        coords = geo.decode_polyline(route["geometry"], precision=6)
        durations = [d for leg in route["legs"] for d in leg["annotation"]["duration"]]
        if len(durations) != len(coords) - 1:
            durations = [0.0] * (len(coords) - 1)
            _spread_time(coords, 0, len(coords) - 1, route["duration"], durations)
        # OSRM uses car speeds; no segment may be faster than a truck's top speed.
        segment_seconds = [
            max(seconds, geo.haversine_miles(a, b) / TRUCK_TOP_SPEED_MPH * 3600)
            for seconds, a, b in zip(durations, coords, coords[1:])
        ]
        roads = Counter()
        for leg in route["legs"]:
            for name in filter(
                None, (n.strip() for n in leg.get("summary", "").split(","))
            ):
                roads[name] += leg["distance"] / METERS_PER_MILE
        return _build_route(
            coords, segment_seconds, _label_from_roads(roads), self.name
        )


def _providers() -> list:
    return [ValhallaProvider(settings.VALHALLA_URL), OsrmProvider(settings.OSRM_URL)]


def _is_distinct(candidate: Route, existing: list[Route]) -> bool:
    return all(
        geo.overlap_ratio(candidate.coords, other.coords, candidate.cum_miles)
        < MAX_OVERLAP
        for other in existing
    )


def _detour_points(fastest: Route, origin: LatLon, destination: LatLon) -> list[LatLon]:
    straight = geo.haversine_miles(origin, destination)
    (midpoint,) = geo.points_at_miles(
        fastest.coords, fastest.cum_miles, [fastest.distance_miles / 2]
    )
    heading = geo.bearing_deg(origin, destination)
    return [
        geo.destination_point(
            midpoint, heading + side, min(max(straight * fraction, 10.0), 200.0)
        )
        for fraction in DETOUR_FRACTIONS
        for side in (90, -90)
    ]


def _fill_with_detours(
    provider, routes: list[Route], origin: LatLon, destination: LatLon, load_lb: float
) -> list[Route]:
    fastest = min(routes, key=lambda r: r.duration_seconds)
    vias = _detour_points(fastest, origin, destination)

    def fetch(via: LatLon) -> Route | None:
        try:
            return provider.routes([origin, via, destination], load_lb, alternates=0)[0]
        except RoutingError as exc:
            logger.info("Detour via %s skipped: %s", via, exc)
            return None

    with ThreadPoolExecutor(max_workers=2) as pool:
        candidates = [route for route in pool.map(fetch, vias) if route]
    for candidate in candidates:
        if len(routes) >= ROUTE_COUNT:
            break
        if (
            candidate.duration_seconds <= fastest.duration_seconds * MAX_DURATION_RATIO
            and _is_distinct(candidate, routes)
        ):
            routes.append(candidate)
    return routes


def _dedupe(routes: list[Route]) -> list[Route]:
    unique: list[Route] = []
    for route in routes:
        if _is_distinct(route, unique):
            unique.append(route)
    return unique


def get_route_options(
    origin: LatLon, destination: LatLon, load_lb: float
) -> list[Route]:
    """Up to three distinct truck routes, fastest first."""
    key_source = f"{origin[0]:.5f},{origin[1]:.5f}|{destination[0]:.5f},{destination[1]:.5f}|{round(load_lb, -3)}"
    cache_key = "routes:v1:" + hashlib.sha256(key_source.encode()).hexdigest()
    cached = cache.get(cache_key)
    if cached is not None:
        return cached

    last_error: RoutingError | None = None
    for provider in _providers():
        try:
            routes = _dedupe(
                provider.routes(
                    [origin, destination], load_lb, alternates=ROUTE_COUNT - 1
                )
            )
        except NoRouteFound:
            raise
        except RoutingError as exc:
            logger.warning("Routing provider %s failed: %s", provider.name, exc)
            last_error = exc
            continue
        if len(routes) < ROUTE_COUNT:
            routes = _fill_with_detours(provider, routes, origin, destination, load_lb)
        routes = sorted(routes, key=lambda r: r.duration_seconds)[:ROUTE_COUNT]
        cache.set(cache_key, routes, CACHE_TTL_SECONDS)
        return routes
    raise RoutingError(
        str(last_error) if last_error else "No routing provider available"
    )
